# ---- VectorCraft helpers: each returns command steps ----
def doc(w, h):
    return [{'command': 'file.new', 'params': {'width': w, 'height': h, 'units': 'Pixels', 'backgroundContents': 'transparent', 'colorMode': 'rgb'}}]

def paint(stroke=None, weight=1, fill=None, dash=None, cap='butt', join='miter'):
    steps = [{'command': 'paint.setFill', 'params': {'color': fill} if fill else {'none': True}},
             {'command': 'paint.setStroke', 'params': {'color': stroke} if stroke else {'none': True}}]
    if stroke:
        steps.append({'command': 'stroke.set', 'params': {'weight': weight, 'cap': cap, 'join': join, 'dash': dash}})
    return steps

def circle(cx, cy, r, **style):
    return [{'command': 'shape.ellipse', 'params': {'x': cx - r, 'y': cy - r, 'width': 2 * r, 'height': 2 * r}}] + paint(**style)

def ticks(cx, cy, r, count, length, width, stroke):
    # A thick dashed circle: each dash is one radial tick, `length` deep and `width` wide.
    gap = 2 * math.pi * r / count - width
    return circle(cx, cy, r, stroke=stroke, weight=length, dash=[round(width, 3), round(gap, 3)])

def polygon(cx, cy, r, sides, rotation=0, **style):
    return [{'command': 'shape.polygon', 'params': {'cx': cx, 'cy': cy, 'radius': r, 'sides': sides, 'rotation': rotation}}] + paint(**style)

def rect(x, y, w, h, radius=0, **style):
    return [{'command': 'shape.rectangle', 'params': {'x': x, 'y': y, 'width': w, 'height': h, 'radius': radius}}] + paint(**style)

def line(*points, **style):
    return [{'command': 'path.create', 'params': {'anchors': [{'x': x, 'y': y} for x, y in points]}}] + paint(**style)

def shape(d, **style):
    return [{'command': 'path.create', 'params': {'d': d}}] + paint(**style)

def effect(name, **params):
    return [{'command': 'effect.apply', 'params': {'effect': name, 'params': params}}]

def turn_half(w, h):
    # Rotate the whole drawing 180° about the artboard: a top-left corner becomes bottom-right.
    return [{'command': 'select.all', 'params': {}}, {'command': 'object.transform', 'params': {'matrix': [-1, 0, 0, -1, w, h]}}]

