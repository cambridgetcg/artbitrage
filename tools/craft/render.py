# ---- DesignCraft mockups: the page laid out from the assets before it is built in HTML ----
MINCHO = 'Shippori Mincho'  # bundled with DesignCraft; its default face has no CJK glyphs

class Layout:
    """Collects DesignCraft steps; refs give "$N.id" for a frame made earlier in the run."""
    def __init__(self, w, h, title):
        self.steps = [('file.new', {'intent': 'web', 'units': 'pixels', 'width': w, 'height': h, 'pages': 1, 'facingPages': False, 'margins': 0, 'title': title})]
    def add(self, cmd, params=None):
        self.steps.append((cmd, params or {}))
        return f'${len(self.steps) - 1}.id'
    def swatches(self, **colors):
        for name, color in colors.items():
            self.add('swatch.create', {'name': name, 'color': color})
    def box(self, rect, fill=None, stroke=None, weight=1, opacity=None):
        ref = self.add('frame.create', {'rect': rect, 'content': 'unassigned'})
        if fill: self.add('object.fill', {'swatch': fill})
        if stroke: self.add('object.stroke', {'swatch': stroke, 'weight': weight})
        if opacity is not None: self.add('object.opacity', {'opacity': opacity})
        return ref
    def image(self, path, x, y, width, opacity=None, blend=None):
        self.add('file.place', {'path': str(ROOT / path), 'x': x, 'y': y, 'width': width})
        if opacity is not None or blend: self.add('object.opacity', {'opacity': 1 if opacity is None else opacity, **({'blend': blend} if blend else {})})
    def text(self, rect, words, center=False, **attrs):
        ref = self.add('frame.create', {'rect': rect, 'content': 'text', 'text': words})
        self.add('text.selectStory', {'frame': ref})
        self.add('type.char', {'attrs': attrs})
        if center: self.add('type.alignCenter')

