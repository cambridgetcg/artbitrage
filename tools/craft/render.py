def sha256(data):
    return hashlib.sha256(data).hexdigest()

def version(tool):
    return subprocess.run([CLI[tool], '--version'], capture_output=True, text=True).stdout.strip() or 'unknown'

def render(name):
    room, file, tool, recipe, new = ASSETS[name]
    out = ROOT / 'assets' / room / file
    out.parent.mkdir(parents=True, exist_ok=True)
    steps = recipe()
    if tool == 'vectorcraft':
        with tempfile.NamedTemporaryFile('w', suffix='.json', delete=False) as f:
            json.dump(steps, f)
        args = [CLI[tool], 'run', '--commands', f.name, '--export', str(out)]
        recorded = steps
    else:
        args = [CLI[tool], 'run', '--new', json.dumps({**new, 'name': name})]
        for cmd, params in steps:
            args += ['--cmd', cmd, '--params', json.dumps(params)]
        args += ['--out', str(out), '--quality', '84']
        recorded = {'new': new, 'steps': [{'command': c, 'params': p} for c, p in steps]}
    run = subprocess.run(args, capture_output=True, text=True)
    if run.returncode:
        sys.exit(f'{name}: {tool} failed\n{run.stdout[-2000:]}\n{run.stderr[-2000:]}')
    body = out.read_bytes()
    entry = {'file': file, 'tool': tool, 'version': version(tool), 'recipe': f'tools/craft/render.py {name}',
             'recipe_sha256': sha256(json.dumps(recorded, sort_keys=True).encode()), 'bytes': len(body), 'sha256': sha256(body),
             'rendered': date.today().isoformat()}
    record = ROOT / 'assets' / room / 'crafting.json'
    data = json.loads(record.read_text()) if record.exists() else {
        'about': f'Art for /{room}, drawn with the ArtCraft team\'s Crafting Apps from the command recipes in tools/craft/render.py. No model generated these files and no reference image was used; the room is a homage in our own ink.',
        'tools': RELEASES, 'assets': []}
    data['assets'] = [a for a in data['assets'] if a['file'] != file] + [entry]
    data['assets'].sort(key=lambda a: a['file'])
    record.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n')
    print(f'{name}: {out.relative_to(ROOT)} {len(body)} bytes')

def mockup(name):
    room, file, recipe = MOCKUPS[name]
    out = ROOT / file
    out.parent.mkdir(parents=True, exist_ok=True)
    args = [CLI['designcraft'], 'run']
    for cmd, params in recipe():
        args += ['--cmd', f'{cmd}={json.dumps(params, ensure_ascii=False)}']
    run = subprocess.run(args + ['--export', str(out)], capture_output=True, text=True)
    if run.returncode:
        sys.exit(f'{name}: designcraft failed\n{run.stdout[-2000:]}\n{run.stderr[-2000:]}')
    print(f'{name}: {file} {out.stat().st_size} bytes')

if __name__ == '__main__':
    names = sys.argv[1:] or [*ASSETS, *MOCKUPS]
    unknown = [n for n in names if n not in ASSETS and n not in MOCKUPS]
    if unknown:
        sys.exit(f'unknown asset: {", ".join(unknown)} (known: {", ".join([*ASSETS, *MOCKUPS])})')
    for n in names:
        (render if n in ASSETS else mockup)(n)
